// ★★★ THE CITY'S OWN BOOK OF ITSELF, 1878 — AND IT PRINTS THE FEB. 1874
// RENAMING ORDINANCE IN FULL.
//
// Wm. M. Caswell compiled every ordinance and resolution the Common Council of
// Los Angeles had passed and left in force, from the Mexican-era land
// ordinances of 1852 down to July 1878, bound them behind the Revised Charter
// of April 1878, and indexed the lot by subject. 552 leaves; 736 numbered
// sections; two indexes.
//
// ⚠ THERE ARE NO ORDINANCE NUMBERS IN THIS BOOK, AND THERE CANNOT BE. Los
// Angeles did not number its ordinances until No. 104 of November 1883. What
// Caswell prints in the outer margin is HIS OWN SECTION NUMBER, §1 to §736,
// running across ordinances and resolutions alike. Both indexes are keyed to
// it. Cite as `Caswell 1878, §N (p. N)`. Anyone who turns a Caswell section
// number into an "Ordinance No." has invented a fact.
//
// ⚠ THIS DOCUMENT HAS NO ROWS AND CARRIES NONE YET. The project is mid-decision
// about how old-series instruments should be identified (CLAUDE.md; the
// switchover status note), and a compilation is not the instrument anyway: each
// section is a separate act with its own adoption and publication dates, and a
// row belongs on the act, not on the book that reprints it. This file exists so
// that what the book says has a stable home and an id, and so the shortlist
// beside it can be cited.
//
// ★ THE TWO FILES BESIDE THIS ONE ARE THE POINT.
//   • `caswell-1878-contents.md` — both indexes transcribed line by line and
//     eye-checked against the page images, the PDF↔folio offset table (it
//     changes TWICE; Gale inserts citation leaves at PDF 201, 402 and 552), and
//     the full text of every renaming instrument in the volume.
//   • `caswell-1878-street-ordinances.md` — the shortlist: every entry that
//     names, renames, vacates, opens, extends, widens, grades or defines the
//     lines of a street, renamings first.
//
// ⭐⭐⭐ WHAT IT SETTLED ON THE FIRST READING (2026-09-19):
//   • §394, p. 215 — THE FEBRUARY 26, 1874 ORDINANCE, PRINTED IN FULL. The
//     project held it only as a minutes copy (documents/ord-1874-02-26) with a
//     doubt about whether it made one renaming or three. It made THREE, in ONE
//     instrument: Grasshopper→Pearl, Bull→Castelar, Wasp→Yale. Unqualified; no
//     extents. Caswell's copy reads "Approved." with NO DATE, where §393 from
//     the same sitting carries "Approved Feb. 27th, 1874" — so the printed
//     compilation does not corroborate the approval date the ledger gives.
//   • §578, p. 349 — ETERNITY STREET → BUENA VISTA STREET, adopted 30 Dec.
//     1875, published 4 Jan. 1876. ⚠⚠ TWELVE YEARS EARLIER than the 1888 this
//     project carries from Kines. See FINDINGS.md; this wants Kenny's decision.
//   • §678, p. 452 — NEGRO ALLEY made part of LOS ANGELES STREET, 22 Mar. 1877,
//     with a metes-and-bounds running from A. F. Coronel's adobe to H.
//     Newmark's. A merger, not a rename.
//   • §702, p. 477 — LOVER'S LANE → DATE STREET, 22 Nov. 1877, "situated
//     northerly of Macy street" — a renaming WITH an extent.
//   • §244, p. 145 — JAIL STREET → FRANKLIN STREET, approved 3 Apr. 1872.
//   • §536, p. 300 — SHORT STREET, DEFINING LINES. The street this project
//     could not place: ~1,062 ft in three legs north-west from the west line of
//     Eternity street to Canal and Reservoir street, ~60 ft wide, with A.
//     Olivas's adobe at the corner of Short and Eternity. Both termini are now
//     named streets. Short Street is placed.
//   • §285, p. 154 — Manuel REQUENA's donated street, First to Commercial
//     between Los Angeles and Alameda, is "to be known and called WILMINGTON
//     STREET." He gave the ground; the council put another name on it.
//   • §680, p. 454 — "heretofore known as VINE OR OLVERA STREET, will hereafter
