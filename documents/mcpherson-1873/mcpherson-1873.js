// they do not interchange:
//   1. Part Second, Chapter N, Section S — the revised code. Section numbers
//      run 1–366 straight through all thirty-five chapters, so a section number
//      alone is unique. Streets are Chapter XXVI, §§292–348.
//   2. Appendix No. 1, No. n / Appendix No. 3, No. n — McPherson's own running
//      numbers, 1–17 in EACH appendix. ⚠ "App. 1 No. 13" and "App. 3 No. 13"
//      are different instruments; the appendix must always be named.
//   3. City Archives / City Records, Vol. VII, p. N — printed under each
//      appendix ordinance. The only handle that points past this book at the
//      original record, and the one an archive request should quote.
//
// ⚠⚠ DATE. This document's `date` is the compilation, 1873. NOTHING in the
// book should be dated to 1873 on that account: every instrument carries its
// own approval date, from Jan. 1852 to March 1873, and a row built on one must
// take the INSTRUMENT's date (§4.1). Worse, the preface sets a trap:
//
//   "Whenever the phrase, 'Approved June 1st, 1869,' occurs, it means that the
//    sections preceding it … are taken from the pamphlet, 'Revised Ordinances
//    … approved June 1st, 1869,' and not the date of their original approval by
//    the Common Council and Mayor, (as many of the original copies are lost.)"
//
