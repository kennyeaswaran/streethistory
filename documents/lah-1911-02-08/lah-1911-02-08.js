// STAGE 1 — ASKED, WON, AND THEN UNWON. The sequence in one meeting:
//
//   • The University of Southern California and other property owners petition to change
//     **Wesley avenue, from Jefferson to Santa Monica, to University avenue.**
//   • The **city engineer reports AGAINST**, on the ground that Wesley avenue has borne
//     that name for **30 years** and confusion would arise. (That dates the name to about
//     1881.)
//   • Councilman Williams, **who lives in the district**, moves to set the engineer's
//     recommendation aside. Carried **6 to 3** — Gregory, O'Brien and Stewart against.
//   • O'Brien then campaigns for fifteen or twenty minutes and gets the matter
//     **reconsidered and sent to the streets committee.**
//
// So a renaming can be voted through and undone inside a single meeting. A minute book
// showing the 6-to-3 vote without the reconsideration would be actively misleading —
// which is a sharper version of "adoption is not law."
//
// The two grounds of objection are the two we see everywhere: **long use** (the engineer,
// as in documents/lah-1899-05-06 and documents/dnla-1932-03-22) and **cost**, implicitly
// (documents/lah-1910-09-30, $100 a street).
//
// Also in this clipping, for the Hoover Street file: the council ordered Hoover street
// paved from Twenty-eighth to Thirty-second, leaving the portion between Thirty-second
// and Jefferson unpaved — and Councilman Williams, who owns property fronting it, was
// vigorously opposed because he would be "stung for about $15000 assessment." A street
// name change and a street improvement, decided by the same man's frontage.
//
