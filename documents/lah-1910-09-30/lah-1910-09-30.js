// THE RULE FOR ANNEXED DISTRICTS, stated plainly, and the most quotable line in the
// batch for anyone trying to reason about which of two same-named streets kept its
// name:
//
//   "In nearly all cases the names of the streets in the original city are to be left as
//   they are and those in the annexed portions changed."
//
// This is the same seniority principle Pasadena applied in 1899
// (documents/lah-1899-10-11), now as standing Los Angeles policy after the 1909 harbor
// consolidation. Named consequences: Beacon street in San Pedro loses its name and
// Beacon street in Los Angeles keeps it; ALL the numbered streets of Wilmington and San
// Pedro must change; conflicting Hollywood and Colegrove streets change too.
//
// The second half is a fact we have not had anywhere else — the PRICE of a renaming.
// Assistant city engineer J. J. Johnson: about $100 per street to change the name on
// the department's records, maps, profiles and other documents. That is the department's
// reason for resisting sentimental renamings, and it explains the tone of the
// engineer's objections in 1911 and after.
//
