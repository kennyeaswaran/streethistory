// ★★ A DOCUMENT ABOUT THE MACHINERY ITSELF, and the most candid thing in this
// whole search about why the record is such a tangle.
//
// The city attorney, asked to draft an ordinance changing South Street to Tenth
// Street, reports that the CITY ENGINEER has asked for all renaming ordinances to
// be referred to his department instead, "for reason that his department has all
// the data and maps on these subjects, and is better qualified to report upon the
// same. MUCH CONFUSION FREQUENTLY ARISES FROM THE CHANGE OF NAMES OF STREETS, and
// we are sometimes ordered to present ordinances to improve streets under private
// contract when the grades of such streets have not been established."
//
// WHAT IT TELLS THE PROJECT. Until 1896 the office drafting renaming ordinances
// was not the office holding the maps. That is the mechanical explanation for a
// lot of what this corpus contains: extents that do not resolve, streets renamed
// twice, names given to two streets at once, and the "Mateo, or Shafer, street"
// kind of entry where the drafter is not sure what the street is currently called.
//
// SOUTH STREET is the same street the Aug. 1896 ordinance makes into Western
// Avenue and the Dec. 1896 one makes into Union Avenue
// (documents/lah-1896-09-03, lah-1896-12-29). Three proposed names in seven months.
//
