// WHY THE ORDINANCE WAS RECALLED, in the residents' own terms — and the funniest piece
// of writing in the whole run. The Herald's framing: either the Sixth ward moves, or
// the whole town slides sideways and Eighth street is rechristened First, with the
// lanes between named Monday boulevard, Tuesday lane, Wednesday place "after the days
// of the week."
//
// The substantive objection is one every renaming project meets: "residents of the
// section dislike going to bed one night on one street and waking up and finding their
// street has moved six or seven blocks away, leaving them on another." That is exactly
// what a renumbering does, and it is why so many of these ordinances fail.
//
