// now Sunset Boulevard and Chavez Avenue. This ordinance is the join: on January
// 24, 1885 the city declared those two streets to be one street and called it
// Bellevue avenue. `bellevue-ave` said only "It predates the 1886 Angeleno
// Heights tract"; here is the day it was made.
//
// ★ IT ALSO PLACES "SHORT", WHICH handbook/WANTED.md P2 lists as a street the
// project cannot put on the ground. Section 1 runs it "from upper Main street to
// Canal and Reservoir street"; Resolution No. 313 of this same volume defines its
// limits "from Buena Vista street westerly to Canal and Reservoir street and
// dedicating the same to public uses as a street"; and Resolutions 232, 246, 309
// and 310 grade Buena Vista street "between High and Short". So Short ran west
// from Upper Main, crossed Buena Vista, and ended where Beaudry's Canal and
// Reservoir Street began — with High Street (later Walters, Ord. 257 of this
// volume) as its neighbour on Buena Vista.
//
// WHY BOTH ROWS ARE `whole-name` AND NOT `extent`. The from–to clauses in
// Section 1 are IDENTIFICATIONS, not qualifiers: each says which street is meant
// ("the street extending from upper Main street to Canal and Reservoir street,
