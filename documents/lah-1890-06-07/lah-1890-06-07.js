// changing the names of streets."
//
// So by 1890 the council had a standing pipeline: individual requests were parked
// until enough accumulated for an omnibus. That explains the rhythm this batch
// shows — a scatter of single-street ordinances punctuated by big lists in 1889,
// 1896 and 1897 — and it means a renaming's DATE can be years after the request.
//
