// ★ RENAMING AS A PRECONDITION OF A PUBLIC WORK — the same mechanism as the Loomis
// Street ordinance eight months earlier (documents/lah-1893-02-21), and stated
// very plainly here:
//
// "In the matter of the proposed opening of SUNSET BOULEVARD from the Sisters'
// hospital to the city boundary, I find that before the necessary ordinance of
// intention can be passed it will be necessary to CHANGE THE NAMES OF CERTAIN
// STREETS WHICH WILL BECOME PARTS OF SAID BOULEVARD."
//
// So the boulevard is named before it exists as a road, by consolidating the
// names of the pieces it will be made of. The published ordinance five days later
// lists them (documents/lah-1893-10-29).
//
// This is the clearest statement in the corpus of WHY continuity renamings
// happened: not tidiness, but that a street cannot legally be opened along a line
// that carries five names.
//
