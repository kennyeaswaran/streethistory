// ★★ A CHANGE THAT DID NOT HAPPEN — and the only reason we would ever know is this
// clipping. Sunset Boulevard still runs from the Plaza to Hillhurst today; Hollywood
// Boulevard does not begin downtown. So an 8-to-5 council order, backed by petitions
// from improvement associations, produced nothing.
//
// That makes it the most useful kind of document we have: **evidence against a change**.
// Without it, a later researcher finding a 1928 reference to "Hollywood Boulevard" east
// of Hollywood would have no way to know an ordinance had been ordered and abandoned.
//
// QUALIFIED: the Plaza to Hillhurst avenue — that is the whole eastern half of Sunset,
// from the founding Plaza of Los Angeles out to Los Feliz.
//
// The politics are unusually legible:
//   FOR — Councilmen Randall (mover) and Foster (second); Councilman Shaw; Henry E.
//         Holbrook; Greely Kolts, former councilman; A. J. Barnes, former councilman
//         ("will be an asset to Hollywood"); Captain E. Z. Collings; several improvement
//         associations by petition.
//   AGAINST — Carl Bush of the **Hollywood Chamber of Commerce**; Harry Bain of the
//         **Hollywood Boulevard Improvement Association**; E. F. Bogardus, Miss Helen
//         Hogan, A. Z. Taft and **C. E. Toberman**.
//
// Note who is against: Hollywood's own chamber of commerce and its own boulevard
// association did not want Hollywood Boulevard extended downtown. That is the exact
// shape of the 1908 Wilshire fight (documents/lah-1908-07-14) — the prestigious street
// refusing to share its name with a longer, plainer one. Councilman Randall's retort,
// that the arguments against "are based on materialism," is the same complaint from the
// other side.
//
// The planning committee's majority report — that a petition from a majority of property
// owners along the entire length of Sunset be obtained first, and the sentiment of
// Hollywood Boulevard owners taken — was REJECTED 8 to 5 before the order passed. So
// the council deliberately skipped the consultation step, which may be why nothing came
// of it.
//
