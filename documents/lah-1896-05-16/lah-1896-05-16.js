// WHAT IS PROPOSED: Buena Vista Street from Bellevue Avenue north to the river,
// and Pasadena Avenue from there to the city limits, to become PASADENA
// BOULEVARD; and the cross streets from Ord north to the city limits to be
// renumbered as AVENUES — Ord to Seventh avenue, ALPINE to Eighth avenue, College
// to Ninth, and on up through Garvanza to Fifty-second avenue.
//
// ★ AND IT IS WHY LOS ANGELES HAS BOTH NUMBERED STREETS AND NUMBERED AVENUES.
// Gen. Allen: "The change of names in the southerly portion of the city to
// numbered streets is expected to prove of great benefit, and it is thought that a
// change in the northerly portion to NUMBERED AVENUES will be a convenience …
// The only objection which can be urged to this change is the fact that the
// streets south of First street are numbered with the same numbers, but it is
// believed that the designation of those north of First street as AVENUES will be
// sufficient to prevent confusion." Streets south of First, avenues north of it —
// stated as a design decision, in May 1896, with the objection to it anticipated
// and answered.
//
// ★★ IT ALSO TOUCHES THE LAST OPEN HUNT IN WANTED.md. Buena Vista Street becomes
// NORTH BROADWAY in Nov. 1909; here, thirteen years earlier, there is a live
