// boulevard and road leading from the city to Pasadena, there being now nothing to
// indicate the connecting road between the two cities." The 1909 renaming was not
// the first attempt to give that road one name.
//
// ⚠ AND `alpine` IS ON THE LIST. Alpine Street — renamed from Virgin in Aug. 1887
