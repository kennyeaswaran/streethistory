// ★★ THE COUNCIL'S ANSWER TO THE VETO, and the most explicit statement of WHY a
// renaming happened that this corpus contains.
//
// Two reasons are given, both by Major Bonsall:
//
//   • CONTINUITY. "Stephenson avenue, for instance, had been suggested in open
//     council as a better name for the east portion of Second street, because of
//     its deflection to the south in Boyle Heights." A street that bends far
//     enough stops being the same street.
//   • CONFUSION. "Another instance where changes were necessary was that of WATER,
//     WATERS AND WALTERS STREETS, which were so much alike as to be confusing."
//     Three names one letter apart. That is the reason behind `waters-street` →
//     Douglas and Walters → Ord in the Oct. 1890 list, and behind High → Walters
//     being undone four years after it was done (documents/lah-1886-09-21).
//
// AND A THIRD THING, about authority: "the board had not acted upon its own accord,
// but had made the changes in accordance with the wishes of the property owners,
// as expressed in petitions to the council." The same claim the Sept. 1896
// petitions make from the other side (documents/min-1896-09-14). Whoever writes
// the history of this campaign will have to weigh those two against Mayor Hazard's
// "without any apparent reason".
//
