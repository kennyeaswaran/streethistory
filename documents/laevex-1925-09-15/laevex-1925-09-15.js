// ★★ THE SAWTELLE SEQUEL, six years on — and the answer to a question left open by
// documents/lah-1919-09-30, which reported the ordinance renaming Sawtelle's streets
// for Civil War battles and did not say what became of it.
//
// It passed, and the residents hated it. Three facts here that no other document in the
// corpus supplies:
//
// 1. **The whole district was renamed "without warning."** Whatever consultation the
//    1919 article implied, the residents say there was none.
// 2. **It was passed under EMERGENCY PROVISIONS**, so "the new names became effective
//    the day after the ordinances were adopted" — no thirty-day wait as in
//    documents/lah-1908-03-13. That is a procedural route we have not seen before, and
//    it means a name can be law within twenty-four hours of a council vote. Any dating
//    that assumes a waiting period can be wrong by a month.
// 3. **"Ordinances", plural** — so the Sawtelle renaming was more than one instrument.
//
// The residents' complaint is the plainest statement in the file of what a mass renaming
// does to the people living under it: they "don't know whether we live in California or
// Halifax."
//
// The petitions went to the city planning commission. What became of THEM is still open;
// the battle names (Shiloh, Corinth, Iowa, Nebraska and so on) largely survive in West
// Los Angeles today, so the repeal presumably failed. Logged in
// handbook/MINUTES-TO-CHECK.md.
//
