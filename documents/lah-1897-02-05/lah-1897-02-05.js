// mechanism is now explicit: the surname was APPENDED, not substituted, which is
// why the name reads the way it does. `nevada-1886` was Forman's name, and the
// 1889 folding-in was to "make it uniform".
//
// WHAT IT ADDS. VIRGINIA STREET, named for Bell's daughter and renamed DELONG by
